  assert.equal(await page.locator('html').getAttribute('data-research-view'),'legacy');
  await page.locator('#topic').selectOption('Technology');
  await page.locator('#year').selectOption('2025');
  assert.equal(await page.locator('#catalogue .paper:visible').count(),4);
  assert.deepEqual((await page.locator('#catalogue .paper:visible th a').allTextContents()).sort(),['Phonex-L1','Phonex-SLM','PhonexCoin','PhonexOS'].sort());
